//! System tray mode for the watcher.
//!
//! Threads:
//! - **main thread**: the `tao` event loop and the tray icon. Windows
//!   delivers tray clicks and menu commands as window messages to the thread
//!   that created the icon, so that thread must keep pumping messages.
//! - **watcher thread**: [`watch::run_with`]. It reports moves back by posting
//!   [`UserEvent`]s through an `EventLoopProxy`, which wakes the event loop.
//!   The tray sends commands back through a [`watch::Controller`].
//!
//! If the tray can't be created (or on other platforms), the watcher runs
//! headless on the current thread instead.

use anyhow::Result;

use crate::watch::{self, RecentMove};
use crate::win::SingleInstance;

/// Runs `tao watch` / `taow.exe`: with a tray icon unless `headless` is set
/// or no tray is available.
pub fn run_watch(headless: bool) -> Result<()> {
    // Sign-in startup plus a manual `tao watch` (or `install`, which also
    // starts one) would otherwise race each other for the same files.
    let Some(_instance) = SingleInstance::acquire(crate::win::WATCHER_MUTEX)? else {
        tracing::info!("another watcher is already running; exiting");
        return Ok(());
    };
    if headless {
        return watch::run_headless();
    }
    #[cfg(windows)]
    {
        // Only returns if the tray could not be set up; once the event loop
        // runs, the process ends from inside it.
        let e = imp::run();
        tracing::error!("tray icon unavailable ({e:#}); running without it");
    }
    watch::run_headless()
}

/// Longest tooltip Windows shows: `NOTIFYICONDATAW::szTip` holds 128 UTF-16
/// units including the terminating NUL.
const TOOLTIP_MAX_UTF16: usize = 127;
/// Keep menu entries a readable width.
const MENU_LABEL_MAX_CHARS: usize = 60;

/// Truncates to at most `max` UTF-16 code units, adding "…" when cut.
fn clip_utf16(s: &str, max: usize) -> String {
    if s.encode_utf16().count() <= max {
        return s.to_string();
    }
    let mut out = String::new();
    let mut used = 1; // room for the ellipsis
    for ch in s.chars() {
        used += ch.len_utf16();
        if used > max {
            break;
        }
        out.push(ch);
    }
    out.push('…');
    out
}

fn tooltip_text(status: Option<&str>, paused: bool) -> String {
    let title = if paused { "Tao (paused)" } else { "Tao" };
    let text = match status {
        Some(s) => format!("{title}\n{s}"),
        None => title.to_string(),
    };
    clip_utf16(&text, TOOLTIP_MAX_UTF16)
}

/// "report.pdf → Documents", shortened, with `&` escaped: Windows menus
/// treat `&x` as "underline x as the keyboard shortcut", and `&&` is a
/// literal ampersand.
fn menu_label(m: &RecentMove) -> String {
    let name: String = if m.file_name.chars().count() > MENU_LABEL_MAX_CHARS {
        let mut s: String = m.file_name.chars().take(MENU_LABEL_MAX_CHARS - 1).collect();
        s.push('…');
        s
    } else {
        m.file_name.clone()
    };
    format!("{name}  →  {}", m.folder).replace('&', "&&")
}

/// The status line shown before anything happens in this session.
fn initial_status(recent: &[RecentMove]) -> Option<String> {
    recent
        .first()
        .map(|m| format!("Last: {} to {}", m.file_name, m.folder))
}

/// A faded, greyscale copy of an RGBA image, used as the icon while paused.
fn greyed(rgba: &[u8]) -> Vec<u8> {
    rgba.as_chunks::<4>()
        .0
        .iter()
        .flat_map(|p| {
            // Rec. 601 luma, then pulled towards mid-grey so both halves of
            // the symbol stay visible on light and dark taskbars.
            let luma = 0.299 * p[0] as f32 + 0.587 * p[1] as f32 + 0.114 * p[2] as f32;
            let v = (luma * 0.6 + 128.0 * 0.4) as u8;
            [v, v, v, (p[3] as f32 * 0.7) as u8]
        })
        .collect()
}

#[cfg(windows)]
mod imp {
    use std::panic::AssertUnwindSafe;
    use std::path::{Path, PathBuf};
    use std::time::{Duration, Instant};

    use anyhow::{Context, Result};
    use tao_loop::event::{Event, StartCause};
    use tao_loop::event_loop::{ControlFlow, EventLoopBuilder, EventLoopProxy};
    use tray_icon::menu::{Menu, MenuEvent, MenuId, MenuItem, PredefinedMenuItem, Submenu};
    use tray_icon::{Icon, TrayIcon, TrayIconBuilder};

    use super::*;
    use crate::watch::{Control, Controller, WatchEvent, WatchPaths};

    /// 32x32 pixels, 4 bytes (R, G, B, A) each. Generated by
    /// `assets/make-icon.ps1`. `include_bytes!` embeds the file in the .exe
    /// at compile time, so there is nothing to ship alongside it.
    static ICON_RGBA: &[u8] = include_bytes!("../assets/tray-icon.rgba");
    const ICON_SIZE: u32 = 32;
    const _: () = assert!(ICON_RGBA.len() == (ICON_SIZE * ICON_SIZE * 4) as usize);

    /// How long Quit waits for the watcher to finish a move in progress.
    const QUIT_TIMEOUT: Duration = Duration::from_secs(5);

    const ID_SORT: &str = "sort";
    const ID_UNDO: &str = "undo";
    const ID_PAUSE: &str = "pause";
    const ID_CONFIG: &str = "config";
    const ID_QUIT: &str = "quit";
    const ID_RECENT_PREFIX: &str = "recent-";

    /// Everything that wakes the event loop besides OS messages.
    enum UserEvent {
        Menu(MenuEvent),
        Watch(WatchEvent),
        /// The watcher thread ended. `Err` holds a message for the tooltip.
        WatcherExited(std::result::Result<(), String>),
    }

    struct Tray {
        icon: Option<TrayIcon>,
        recent_menu: Submenu,
        /// Menu entries currently in "Recent moves", with what they open.
        recent_items: Vec<(MenuItem, PathBuf)>,
        no_moves: MenuItem,
        sort: MenuItem,
        undo: MenuItem,
        pause: MenuItem,
        controller: Controller,
        status: Option<String>,
        paused: bool,
        watcher_running: bool,
        quit_deadline: Option<Instant>,
    }

    fn icon(paused: bool) -> Result<Icon> {
        let rgba = if paused {
            greyed(ICON_RGBA)
        } else {
            ICON_RGBA.to_vec()
        };
        Icon::from_rgba(rgba, ICON_SIZE, ICON_SIZE).context("bad tray icon data")
    }

    impl Tray {
        fn build(controller: Controller) -> Result<Self> {
            let recent_menu = Submenu::with_id("recent", "Recent moves", true);
            let no_moves = MenuItem::new("No moves yet", false, None);
            recent_menu.append(&no_moves)?;
            let sort = MenuItem::with_id(ID_SORT, "Sort now", true, None);
            let undo = MenuItem::with_id(ID_UNDO, "Undo last move", true, None);
            let pause = MenuItem::with_id(ID_PAUSE, "Pause", true, None);
            let config = MenuItem::with_id(ID_CONFIG, "Open config", true, None);
            let quit = MenuItem::with_id(ID_QUIT, "Quit", true, None);

            let menu = Menu::new();
            menu.append_items(&[
                &recent_menu,
                &PredefinedMenuItem::separator(),
                &sort,
                &undo,
                &pause,
                &PredefinedMenuItem::separator(),
                &config,
                &quit,
            ])?;

            let icon = TrayIconBuilder::new()
                .with_menu(Box::new(menu))
                // Left and right click both open the menu; there's no
                // window to show on left click.
                .with_menu_on_left_click(true)
                .with_tooltip(tooltip_text(None, false))
                .with_icon(icon(false)?)
                .build()
                .context("creating the tray icon")?;

            Ok(Self {
                icon: Some(icon),
                recent_menu,
                recent_items: Vec::new(),
                no_moves,
                sort,
                undo,
                pause,
                controller,
                status: None,
                paused: false,
                watcher_running: true,
                quit_deadline: None,
            })
        }

        fn refresh_tooltip(&self) {
            if let Some(icon) = &self.icon {
                let text = tooltip_text(self.status.as_deref(), self.paused);
                if let Err(e) = icon.set_tooltip(Some(text)) {
                    tracing::warn!("cannot update tray tooltip: {e}");
                }
            }
        }

        fn set_recent(&mut self, recent: &[RecentMove]) {
            // Rebuild the submenu. Removing an item that isn't in it (the
            // placeholder, the first time round) just returns an error.
            for (item, _) in self.recent_items.drain(..) {
                let _ = self.recent_menu.remove(&item);
            }
            let _ = self.recent_menu.remove(&self.no_moves);
            if recent.is_empty() {
                let _ = self.recent_menu.append(&self.no_moves);
            }
            for (i, m) in recent.iter().enumerate() {
                let id = MenuId::new(format!("{ID_RECENT_PREFIX}{i}"));
                let item = MenuItem::with_id(id, menu_label(m), true, None);
                if let Err(e) = self.recent_menu.append(&item) {
                    tracing::warn!("cannot add recent move to menu: {e}");
                    continue;
                }
                self.recent_items.push((item, m.dest.clone()));
            }
            if self.status.is_none() {
                self.status = initial_status(recent);
                self.refresh_tooltip();
            }
        }

        fn set_paused(&mut self, paused: bool) {
            self.paused = paused;
            self.pause.set_text(if paused { "Resume" } else { "Pause" });
            self.sort.set_enabled(!paused);
            if let (Some(tray), Ok(new_icon)) = (&self.icon, icon(paused))
                && let Err(e) = tray.set_icon(Some(new_icon))
            {
                tracing::warn!("cannot update tray icon: {e}");
            }
            self.refresh_tooltip();
        }

        fn on_watch_event(&mut self, event: WatchEvent) {
            match event {
                WatchEvent::Recent(list) => self.set_recent(&list),
                WatchEvent::Status(s) => {
                    self.status = Some(s);
                    self.refresh_tooltip();
                }
                WatchEvent::Paused(p) => self.set_paused(p),
            }
        }

        fn on_watcher_exited(
            &mut self,
            outcome: std::result::Result<(), String>,
            control_flow: &mut ControlFlow,
        ) {
            self.watcher_running = false;
            if self.quit_deadline.is_some() {
                self.exit(control_flow);
                return;
            }
            // Keep the icon so the user can see what happened, open the
            // config to fix it, and quit.
            for item in [&self.sort, &self.undo, &self.pause] {
                item.set_enabled(false);
            }
            self.status = Some(match outcome {
                Ok(()) => "Watcher stopped".into(),
                Err(e) => format!("Stopped: {e}"),
            });
            self.refresh_tooltip();
        }

        fn on_menu(&mut self, id: &MenuId, control_flow: &mut ControlFlow) {
            let send = |c| {
                if !self.controller.send(c) {
                    tracing::warn!("watcher is not running; ignored {c:?}");
                }
            };
            match id.as_ref() {
                ID_SORT => send(Control::SortNow),
                ID_UNDO => send(Control::UndoLast),
                ID_PAUSE => send(Control::SetPaused(!self.paused)),
                ID_CONFIG => open_config(),
                ID_QUIT => {
                    if self.watcher_running && self.controller.send(Control::Shutdown) {
                        // Exit once the watcher confirms (WatcherExited), or
                        // after a timeout if it's stuck on a slow move.
                        let deadline = Instant::now() + QUIT_TIMEOUT;
                        self.quit_deadline = Some(deadline);
                        *control_flow = ControlFlow::WaitUntil(deadline);
                    } else {
                        self.exit(control_flow);
                    }
                }
                other => {
                    let path = other
                        .strip_prefix(ID_RECENT_PREFIX)
                        .and_then(|i| i.parse::<usize>().ok())
                        .and_then(|i| self.recent_items.get(i))
                        .map(|(_, p)| p.clone());
                    if let Some(path) = path {
                        reveal_in_explorer(&path);
                    }
                }
            }
        }

        fn exit(&mut self, control_flow: &mut ControlFlow) {
            // Drop the icon explicitly: `run` ends the process with `exit`,
            // which skips destructors, and an icon that is never removed
            // lingers in the tray until the mouse passes over it.
            self.icon.take();
            *control_flow = ControlFlow::Exit;
        }
    }

    fn open_config() {
        let result = crate::paths::config_file().and_then(|path| {
            crate::config::ensure_exists(&path)?;
            crate::win::open_in_editor(&path)
        });
        if let Err(e) = result {
            tracing::error!("cannot open config: {e:#}");
        }
    }

    /// Opens the file's folder in Explorer with the file selected, or just
    /// the folder if the file has gone.
    fn reveal_in_explorer(path: &Path) {
        use std::os::windows::process::CommandExt;
        let mut cmd = std::process::Command::new("explorer.exe");
        if path.exists() {
            // Explorer parses its own command line instead of following the
            // usual C runtime quoting rules, and expects exactly
            // `/select,"C:\path with spaces\file.pdf"`. `raw_arg` passes
            // that through untouched; `arg` would quote the whole thing.
            cmd.raw_arg(format!("/select,\"{}\"", path.display()));
        } else if let Some(dir) = path.parent().filter(|d| d.is_dir()) {
            cmd.arg(dir);
        } else {
            tracing::warn!("{} no longer exists", path.display());
            return;
        }
        // Don't wait: Explorer hands off to the running shell and exits
        // (with exit code 1, even on success).
        if let Err(e) = cmd.spawn() {
            tracing::error!("cannot start Explorer: {e}");
        }
    }

    fn spawn_watcher(
        inbox: watch::Inbox,
        proxy: EventLoopProxy<UserEvent>,
    ) -> std::io::Result<std::thread::JoinHandle<()>> {
        std::thread::Builder::new()
            .name("watcher".into())
            .spawn(move || {
                let result = std::panic::catch_unwind(AssertUnwindSafe(|| {
                    let locations = WatchPaths::standard()?;
                    watch::run_with(&locations, inbox, |e| {
                        // Fails only once the event loop has gone, i.e. we're quitting.
                        let _ = proxy.send_event(UserEvent::Watch(e));
                    })
                }));
                let outcome = match result {
                    Ok(Ok(())) => Ok(()),
                    Ok(Err(e)) => {
                        tracing::error!("watcher stopped: {e:#}");
                        Err(format!("{e:#}"))
                    }
                    // The panic hook has already logged the details.
                    Err(_) => Err("internal error, see the log".into()),
                };
                let _ = proxy.send_event(UserEvent::WatcherExited(outcome));
            })
    }

    /// Sets up the tray and runs the event loop. Never returns on success;
    /// returns the error if the tray could not be created.
    pub fn run() -> anyhow::Error {
        match setup() {
            Ok(never) => match never {},
            Err(e) => e,
        }
    }

    fn setup() -> Result<std::convert::Infallible> {
        let event_loop = EventLoopBuilder::<UserEvent>::with_user_event().build();
        let (controller, inbox) = watch::control_channel();
        // Create the icon before starting the watcher, so a tray failure
        // leaves nothing running and the caller can fall back to headless.
        let mut tray = Tray::build(controller)?;

        // muda (the menu crate) calls this from the event loop's thread
        // when a menu item is clicked; forward it into the loop.
        let menu_proxy = event_loop.create_proxy();
        MenuEvent::set_event_handler(Some(move |e| {
            let _ = menu_proxy.send_event(UserEvent::Menu(e));
        }));

        spawn_watcher(inbox, event_loop.create_proxy()).context("starting watcher thread")?;

        event_loop.run(move |event, _, control_flow| {
            if tray.quit_deadline.is_none() {
                *control_flow = ControlFlow::Wait;
            }
            match event {
                Event::UserEvent(UserEvent::Menu(e)) => tray.on_menu(&e.id, control_flow),
                Event::UserEvent(UserEvent::Watch(e)) => tray.on_watch_event(e),
                Event::UserEvent(UserEvent::WatcherExited(outcome)) => {
                    tray.on_watcher_exited(outcome, control_flow)
                }
                Event::NewEvents(StartCause::ResumeTimeReached { .. })
                    if tray.quit_deadline.is_some() =>
                {
                    tracing::warn!("watcher did not stop in time; quitting anyway");
                    tray.exit(control_flow);
                }
                _ => {}
            }
        })
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::path::PathBuf;

    fn mv(name: &str, folder: &str) -> RecentMove {
        RecentMove {
            file_name: name.into(),
            folder: folder.into(),
            dest: PathBuf::from(folder).join(name),
        }
    }

    #[test]
    fn menu_labels_escape_ampersands_and_shorten() {
        assert_eq!(menu_label(&mv("a.pdf", "Documents")), "a.pdf  →  Documents");
        assert_eq!(
            menu_label(&mv("Tom & Jerry.mp4", "Video")),
            "Tom && Jerry.mp4  →  Video"
        );
        let long = "x".repeat(100) + ".zip";
        let label = menu_label(&mv(&long, "Archives"));
        assert!(label.starts_with(&"x".repeat(59)));
        assert!(label.contains("…  →  Archives"));
    }

    #[test]
    fn tooltips_fit_the_windows_limit() {
        assert_eq!(tooltip_text(None, false), "Tao");
        assert_eq!(
            tooltip_text(Some("Moved a.pdf to Documents"), true),
            "Tao (paused)\nMoved a.pdf to Documents"
        );
        let long = "Moved ".to_string() + &"文".repeat(200);
        let t = tooltip_text(Some(&long), false);
        assert!(t.encode_utf16().count() <= TOOLTIP_MAX_UTF16);
        assert!(t.ends_with('…'));
        // Characters outside the BMP take two UTF-16 units; never split one.
        let emoji = "😀".repeat(100);
        let t = clip_utf16(&emoji, 10);
        assert_eq!(t, "😀😀😀😀…");
    }

    #[test]
    fn initial_status_comes_from_the_newest_move() {
        assert_eq!(initial_status(&[]), None);
        assert_eq!(
            initial_status(&[mv("new.png", "Images"), mv("old.pdf", "Documents")]).as_deref(),
            Some("Last: new.png to Images")
        );
    }

    #[test]
    fn greyed_icon_keeps_size_and_transparency() {
        let rgba = include_bytes!("../assets/tray-icon.rgba");
        let grey = greyed(rgba);
        assert_eq!(grey.len(), rgba.len());
        for (src, dst) in rgba
            .as_chunks::<4>()
            .0
            .iter()
            .zip(grey.as_chunks::<4>().0.iter())
        {
            assert_eq!(dst[0], dst[1]);
            assert_eq!(dst[1], dst[2]);
            if src[3] == 0 {
                assert_eq!(dst[3], 0, "transparent pixels stay transparent");
            }
        }
    }
}
